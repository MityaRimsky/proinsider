insert into public.user_live_prediction_assignments (
  user_id,
  live_prediction_id,
  notification_id
)
select distinct
  s.user_id,
  lp.id,
  null::bigint
from public.live_predictions lp
join public.user_live_subscriptions s
  on lp.published_at >= s.starts_at
 and lp.published_at <= s.expires_at
join public.subscription_plans p
  on p.id = s.plan_id
where p.name = 'live'
  and s.status in ('active', 'past_due', 'cancelled', 'expired')
on conflict (user_id, live_prediction_id)
do nothing;

create or replace function public.create_forecast_notification(
  p_forecast_card_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_forecast public.forecast_cards%rowtype;
  v_notification_id bigint;
begin
  select *
    into v_forecast
  from public.forecast_cards
  where id = p_forecast_card_id;

  if not found then
    raise exception 'Forecast card with id % not found', p_forecast_card_id;
  end if;

  if v_forecast.type not in ('premium', 'gold') then
    return null;
  end if;

  insert into public.notifications (
    title,
    plan_type,
    forecast_card_id,
    match_time,
    coefficient
  )
  values (
    'Новый ' || initcap(v_forecast.type) || ' прогноз',
    v_forecast.type,
    v_forecast.id,
    v_forecast.start_time,
    coalesce(v_forecast.total_odds, 0)
  )
  on conflict (forecast_card_id)
  where forecast_card_id is not null
  do nothing
  returning id into v_notification_id;

  if v_notification_id is null then
    select n.id
      into v_notification_id
    from public.notifications n
    where n.forecast_card_id = p_forecast_card_id;
  end if;

  return v_notification_id;
end;
$$;

create or replace function public.create_live_prediction_notification()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_notification_id bigint;
begin
  insert into public.notifications (
    title,
    plan_type,
    forecast_card_id,
    match_time,
    coefficient
  )
  values (
    'Новый Live прогноз',
    'live',
    null,
    null,
    0
  )
  returning id into v_notification_id;

  insert into public.user_live_prediction_assignments (
    user_id,
    live_prediction_id,
    notification_id
  )
  select distinct
    s.user_id,
    new.id,
    v_notification_id
  from public.user_live_subscriptions s
  join public.subscription_plans p
    on p.id = s.plan_id
  where p.name = 'live'
    and s.status in ('active', 'past_due', 'cancelled')
    and coalesce(new.published_at, now()) >= s.starts_at
    and coalesce(new.published_at, now()) <= s.expires_at
  on conflict (user_id, live_prediction_id)
  do update
  set notification_id = excluded.notification_id;

  return new;
end;
$$;

