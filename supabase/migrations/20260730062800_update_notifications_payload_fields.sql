create or replace view public.my_notifications
with (security_invoker = true)
as
select n.*
from public.notifications n
where
(
  n.forecast_card_id is not null
  and exists (
    select 1
    from public.user_forecast_assignments a
    where a.forecast_card_id = n.forecast_card_id
      and a.user_id = auth.uid()
  )
)
or
(
  n.plan_type = 'live'
  and exists (
    select 1
    from public.user_live_prediction_assignments a
    where a.notification_id = n.id
      and a.user_id = auth.uid()
  )
);

create or replace view public.my_live_predictions
with (security_invoker = true)
as
select lp.*
from public.live_predictions lp
where exists (
  select 1
  from public.user_live_prediction_assignments a
  where a.live_prediction_id = lp.id
    and a.user_id = auth.uid()
);

grant select on public.my_notifications to authenticated;
grant select on public.my_live_predictions to authenticated;

