create or replace view public.user_forecast_balances
with (security_invoker = true)
as
select
  balance_rows.user_id,
  balance_rows.plan_id,
  sum(balance_rows.paid_remaining)::integer as paid_remaining,
  sum(balance_rows.bonus_remaining)::integer as bonus_remaining,
  sum(balance_rows.paid_remaining + balance_rows.bonus_remaining)::integer as total_remaining
from (
  select
    c.user_id,
    c.plan_id,
    greatest(c.quantity_granted - c.quantity_used, 0) as paid_remaining,
    0 as bonus_remaining
  from public.user_forecast_credits c

  union all

  select
    b.user_id,
    c.plan_id,
    0 as paid_remaining,
    greatest(b.quantity_granted - b.quantity_used, 0) as bonus_remaining
  from public.user_forecast_bonuses b
  join public.user_forecast_credits c
    on c.id = b.source_credit_id
) balance_rows
group by
  balance_rows.user_id,
  balance_rows.plan_id;