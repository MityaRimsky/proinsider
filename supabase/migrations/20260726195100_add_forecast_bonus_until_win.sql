  on public.user_forecast_assignments(credit_id)
  where credit_id is not null;

create index if not exists idx_user_forecast_assignments_bonus_id
  on public.user_forecast_assignments(bonus_id)
  where bonus_id is not null;

create index if not exists idx_user_forecast_bonuses_user_id
  on public.user_forecast_bonuses(user_id);

create index if not exists idx_user_forecast_bonuses_source_credit_id
  on public.user_forecast_bonuses(source_credit_id);

create index if not exists idx_user_forecast_bonuses_available
  on public.user_forecast_bonuses(user_id, source_credit_id)
  where quantity_used < quantity_granted;

create index if not exists idx_user_forecast_credits_available
  on public.user_forecast_credits(user_id, plan_id)
  where quantity_used < quantity_granted;

