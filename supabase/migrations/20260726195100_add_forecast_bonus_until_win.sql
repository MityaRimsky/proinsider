alter table public.user_forecast_credits
add column if not exists bonus_until_win boolean not null default false;

update public.user_forecast_credits c
set bonus_until_win = o.bonus_until_win
from public.subscription_options o
where o.id = c.option_id;

create table if not exists public.user_forecast_assignments (
  id bigint generated by default as identity primary key,

  user_id uuid not null
    references auth.users(id)
    on delete cascade,

  forecast_card_id bigint not null
    references public.forecast_cards(id)
    on delete cascade,

  credit_id bigint
    references public.user_forecast_credits(id)
    on delete restrict,

  bonus_id bigint,

  bonus_granted boolean not null default false,

  created_at timestamptz not null default now(),

  constraint user_forecast_assignments_one_source_check
    check (
      (credit_id is not null and bonus_id is null)
      or
      (credit_id is null and bonus_id is not null)
    ),

  constraint user_forecast_assignments_user_forecast_unique
    unique (user_id, forecast_card_id)
);

create table if not exists public.user_forecast_bonuses (
  id bigint generated by default as identity primary key,

  user_id uuid not null
    references auth.users(id)
    on delete cascade,

  source_credit_id bigint not null
    references public.user_forecast_credits(id)
    on delete restrict,

  source_assignment_id bigint not null
    references public.user_forecast_assignments(id)
    on delete restrict,

  reason text not null default 'forecast_lost',

  quantity_granted integer not null default 1,

  quantity_used integer not null default 0,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint user_forecast_bonuses_quantity_granted_check
    check (quantity_granted > 0),

  constraint user_forecast_bonuses_quantity_used_check
    check (quantity_used >= 0 and quantity_used <= quantity_granted),

  constraint user_forecast_bonuses_reason_check
    check (reason in ('forecast_lost', 'manual', 'promotion')),

  constraint user_forecast_bonuses_source_assignment_unique
    unique (source_assignment_id)
);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'user_forecast_assignments_bonus_id_fk'
  ) then
    alter table public.user_forecast_assignments
    add constraint user_forecast_assignments_bonus_id_fk
    foreign key (bonus_id)
    references public.user_forecast_bonuses(id)
    on delete restrict;
  end if;
end;
$$;

create index if not exists idx_user_forecast_assignments_user_id
