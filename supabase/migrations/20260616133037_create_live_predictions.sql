create table if not exists public.live_predictions (
  id bigint generated by default as identity primary key,

  prediction_text text not null,
  image_url text,

  published_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_live_predictions_published_at
on public.live_predictions(published_at desc);

alter table public.live_predictions enable row level security;

create policy "live_predictions are readable by everyone"
on public.live_predictions
for select
using (true);
