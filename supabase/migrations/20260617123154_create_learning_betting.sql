create table if not exists public.learning_betting (
  id bigint generated by default as identity primary key,

  category text not null
    check (category in ('outcome', 'total', 'handicap')),

  badge text not null,
  title text not null,
  description text,

  sort_order int not null default 1,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_learning_betting_category_sort
on public.learning_betting(category, sort_order);

alter table public.learning_betting enable row level security;

drop policy if exists "learning_betting are readable by everyone"
on public.learning_betting;

create policy "learning_betting are readable by everyone"
on public.learning_betting
for select
using (true);

